#!/usr/bin/env python3
"""Generate internal/textutil/unifold_table.go, the folding table of the
optional `unicode = full` setting.

In plain words: for every letter and digit that carries an accent or is a
special form (a ligature, a full-width letter, a superscript digit, a
letter with a stroke), the table says which plain letters it stands for,
so that names written in different ways still match.

Python's own Unicode database is used, so nothing is downloaded.
Run it from the repository root, then check the result with gofmt:

    python3 -I scripts/gen-unifold.py && gofmt -l internal/textutil
"""
import sys
import unicodedata

OUT = "internal/textutil/unifold_table.go"

# Letters that carry no decomposition but are written as plain letters
# in names (the basic mode already folds most of them).
EXTRA = {
    "ø": "o", "đ": "d", "ð": "d", "ł": "l", "ı": "i", "ħ": "h", "ŧ": "t",
    "ŀ": "l", "ŉ": "n", "ß": "ss", "æ": "ae", "œ": "oe", "þ": "th",
    "ƀ": "b", "ƈ": "c", "ƌ": "d", "ƒ": "f", "ɠ": "g", "ƙ": "k", "ƚ": "l",
    "ɲ": "n", "ƥ": "p", "ʠ": "q", "ƭ": "t", "ʋ": "v", "ƴ": "y", "ƶ": "z",
    "ȥ": "z", "ɇ": "e", "ɉ": "j", "ɍ": "r", "ɏ": "y", "ꝁ": "k",
}

# Blocks left out: they are not written in company names, and Hangul and
# CJK compatibility ideographs would only make the table large.
SKIP = [
    (0xAC00, 0xD7A3),    # Hangul syllables
    (0xF900, 0xFAFF),    # CJK compatibility ideographs
    (0xFB1D, 0xFB4F),    # Hebrew presentation forms
    (0xFB50, 0xFDFF),    # Arabic presentation forms A
    (0xFE70, 0xFEFF),    # Arabic presentation forms B
    (0x1D400, 0x1D7FF),  # mathematical letters and digits
    (0x2F800, 0x2FA1F),  # CJK compatibility ideographs supplement
]


def skipped(cp):
    return any(lo <= cp <= hi for lo, hi in SKIP)


def plain(s):
    """Decompose, fold case, drop marks and anything not a letter or digit."""
    s = unicodedata.normalize("NFKD", s).casefold()
    s = unicodedata.normalize("NFKD", s)
    for k, v in EXTRA.items():
        s = s.replace(k, v)
    return "".join(c for c in s if unicodedata.category(c)[0] in "LN")


def esc(s):
    out = []
    for c in s:
        if c.isascii() and c.isalnum():
            out.append(c)
        elif ord(c) <= 0xFFFF:
            out.append("\\u%04x" % ord(c))
        else:
            out.append("\\U%08x" % ord(c))
    return "".join(out)


def main():
    pairs = []
    for cp in range(0x80, 0x110000):
        if skipped(cp):
            continue
        c = chr(cp)
        if unicodedata.category(c)[0] not in "LN":
            continue
        low = c.lower()
        if len(low) == 1 and low != c:
            continue  # Go lowercases it first; its lowercase has an entry.
        if "\u2044" in unicodedata.normalize("NFKD", c):
            continue  # fractions such as ½ would read as 12
        v = EXTRA.get(c) or plain(c)
        if v and v != low:
            pairs.append((c, v))
    lines = []
    row = ""
    for k, v in pairs:
        item = esc(k) + " " + esc(v) + ","
        if len(row) + len(item) > 96:
            lines.append(row)
            row = ""
        row += item
    if row:
        lines.append(row)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Code generated by scripts/gen-unifold.py from Unicode %s; DO NOT EDIT.\n\n"
                % unicodedata.unidata_version)
        f.write("package textutil\n\n")
        f.write("// unifoldTable lists, for the optional full Unicode mode, each\n")
        f.write("// special letter or digit followed by a space, the plain letters it\n")
        f.write("// stands for and a comma. It is read only when the mode is on.\n")
        f.write("const unifoldTable = \"\" +\n")
        for i, l in enumerate(lines):
            end = " +\n" if i < len(lines) - 1 else "\n"
            f.write('\t"%s"%s' % (l, end))
    print("%s: %d entries, Unicode %s" % (OUT, len(pairs), unicodedata.unidata_version), file=sys.stderr)


if __name__ == "__main__":
    main()
